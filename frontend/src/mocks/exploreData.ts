export function mapMockItemToPlace(item: PlaceItem): Place {
  return {
    placeId: item.id,
    name: item.title,
    category: item.category,
    subcategory: item.subcategory || item.tags[0] || 'Khám phá',
    address: item.address,
    phone: item.phone || null,
    website: item.website || null,
    openingHours: item.openingHours || null,
    latitude: item.latitude ?? null,
    longitude: item.longitude ?? null,
    provinceCode: item.provinceCode,
    destinationName: item.province,
    rating: item.rating !== undefined ? item.rating : null,
    reviewCount: item.reviewsCount !== undefined ? item.reviewsCount : null,
    photoUrl:
      item.imageUrl ||
      'https://images.unsplash.com/photo-1528127269322-539801943592?auto=format&fit=crop&w=800&q=80',
    description: item.content?.summary || item.description,
    price: item.price || null,
    tags: item.tags,
    rankingScore: item.rankingScore ?? null,
    hasContent: Boolean(item.hasContent ?? item.content !== null),
    contentLanguage: item.content?.language ?? null,
    content: item.content ?? null,
  };
}

